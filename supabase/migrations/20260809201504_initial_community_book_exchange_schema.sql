create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  abbreviation text,
  created_at timestamptz not null default now(),
  constraint categories_name_not_blank check (btrim(name) <> ''),
  constraint categories_slug_not_blank check (btrim(slug) <> ''),
  constraint categories_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table public.books (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  author text,
  category_id bigint references public.categories (id) on delete set null,
  published_year integer,
  isbn text,
  description text,
  condition public.book_condition,
  status public.book_status not null default 'available',
  cover_path text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint books_title_not_blank check (btrim(title) <> ''),
  constraint books_published_year_reasonable check (
    published_year is null or published_year between 1000 and 2100
  ),
  constraint books_isbn_not_blank check (isbn is null or btrim(isbn) <> '')
);

create table public.book_images (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books (id) on delete cascade,
  storage_path text not null unique,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint book_images_storage_path_not_blank check (btrim(storage_path) <> ''),
  constraint book_images_sort_order_nonnegative check (sort_order >= 0)
);

create table public.borrow_requests (
  id uuid primary key default gen_random_uuid(),
  book_id bigint not null references public.books (id) on delete cascade,
  requester_id uuid not null references public.profiles (id) on delete cascade,
  owner_id uuid not null references public.profiles (id) on delete cascade,
  status public.request_status not null default 'pending',
  message text,
  expires_at timestamptz not null default now() + interval '72 hours',
  responded_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint borrow_requests_participants_differ check (requester_id <> owner_id),
  constraint borrow_requests_message_length check (
    message is null or char_length(message) <= 2000
  ),
  constraint borrow_requests_expiry_after_creation check (expires_at > created_at),
  constraint borrow_requests_responded_after_creation check (
    responded_at is null or responded_at >= created_at
  ),
  constraint borrow_requests_cancelled_after_creation check (
    cancelled_at is null or cancelled_at >= created_at
  )
);

create table public.loans (
  id uuid primary key default gen_random_uuid(),
  request_id uuid unique references public.borrow_requests (id) on delete set null,
  book_id bigint not null references public.books (id) on delete restrict,
  owner_id uuid not null references public.profiles (id) on delete restrict,
  borrower_id uuid not null references public.profiles (id) on delete restrict,
  status public.loan_status not null default 'active',
  started_at timestamptz not null default now(),
  due_at timestamptz not null default now() + interval '21 days',
  returned_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint loans_participants_differ check (borrower_id <> owner_id),
  constraint loans_due_after_start check (due_at > started_at),
  constraint loans_returned_after_start check (
    returned_at is null or returned_at >= started_at
  ),
  constraint loans_returned_status_consistent check (
    status <> 'returned' or returned_at is not null
  )
);

create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  type public.notification_type not null,
  title text not null,
  body text,
  data jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  constraint notifications_title_not_blank check (btrim(title) <> ''),
  constraint notifications_data_is_object check (jsonb_typeof(data) = 'object')
);

