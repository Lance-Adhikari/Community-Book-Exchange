create or replace function public.return_loan(p_loan_id uuid)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_actor_id uuid;
  v_loan public.loans%rowtype;
begin
  v_actor_id := (select auth.uid());

  if v_actor_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  select l.*
  into v_loan
  from public.loans as l
  where l.id = p_loan_id
  for update;

  if not found then
    raise exception 'Loan not found.' using errcode = 'P0002';
  end if;

  if v_actor_id <> v_loan.owner_id and v_actor_id <> v_loan.borrower_id then
    raise exception 'Only a loan participant can mark it returned.' using errcode = '42501';
  end if;

  if v_loan.status <> 'active' and v_loan.status <> 'overdue' then
    raise exception 'Only an active or overdue loan can be returned.' using errcode = 'P0001';
  end if;

  update public.loans
  set status = 'returned',
      returned_at = now()
  where id = v_loan.id;

  update public.books
  set status = 'available'
  where id = v_loan.book_id
    and owner_id = v_loan.owner_id;

  insert into public.notifications (user_id, type, title, body, data)
  values
    (
      v_loan.owner_id,
      'loan_returned',
      'Book returned',
      'The loan has been marked returned.',
      jsonb_build_object('loan_id', v_loan.id, 'book_id', v_loan.book_id)
    ),
    (
      v_loan.borrower_id,
      'loan_returned',
      'Book returned',
      'The loan has been marked returned.',
      jsonb_build_object('loan_id', v_loan.id, 'book_id', v_loan.book_id)
    );
end;
$$;

