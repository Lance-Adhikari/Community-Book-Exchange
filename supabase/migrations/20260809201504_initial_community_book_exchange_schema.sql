-- SECURITY DEFINER is necessary for this atomic transition because clients
-- cannot create loans, alter workflow-controlled book status, or notify users.
create or replace function public.approve_borrow_request(p_request_id uuid)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_actor_id uuid;
  v_book_id bigint;
  v_request public.borrow_requests%rowtype;
  v_book public.books%rowtype;
  v_loan_id uuid;
begin
  v_actor_id := (select auth.uid());

  if v_actor_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  select br.book_id
  into v_book_id
  from public.borrow_requests as br
  where br.id = p_request_id;

  if v_book_id is null then
    raise exception 'Request not found.' using errcode = 'P0002';
  end if;

  -- All approval transactions lock the book before the request.
  select b.*
  into v_book
  from public.books as b
  where b.id = v_book_id
  for update;

  select br.*
  into v_request
  from public.borrow_requests as br
  where br.id = p_request_id
  for update;

  if v_request.owner_id <> v_actor_id
     or v_book.owner_id <> v_actor_id
     or v_request.owner_id <> v_book.owner_id then
    raise exception 'Only the current book owner can approve this request.' using errcode = '42501';
  end if;

  if v_request.status <> 'pending' then
    raise exception 'Only pending requests can be approved.' using errcode = 'P0001';
  end if;

  if v_request.expires_at <= now() then
    raise exception 'This request has expired.' using errcode = 'P0001';
  end if;

  if not v_book.is_active or v_book.status <> 'available' then
    raise exception 'The book is no longer available.' using errcode = 'P0001';
  end if;

  if exists (
    select 1
    from public.loans as l
    where l.book_id = v_book.id
      and l.status in ('active', 'overdue')
  ) then
    raise exception 'The book already has an active loan.' using errcode = '23505';
  end if;

  update public.borrow_requests
  set status = 'approved',
      responded_at = now()
  where id = v_request.id;

  insert into public.loans (
    request_id,
    book_id,
    owner_id,
    borrower_id,
    status,
    started_at,
    due_at
  )
  values (
    v_request.id,
    v_book.id,
    v_book.owner_id,
    v_request.requester_id,
    'active',
    now(),
    now() + interval '21 days'
  )
  returning id into v_loan_id;

  update public.books
  set status = 'borrowed'
  where id = v_book.id;

  with declined as (
    update public.borrow_requests
    set status = 'declined',
        responded_at = now()
    where book_id = v_book.id
      and id <> v_request.id
      and status = 'pending'
    returning requester_id, id
  )
  insert into public.notifications (user_id, type, title, body, data)
  select
    declined.requester_id,
    'request_declined',
    'Book request declined',
    'The book is no longer available.',
    jsonb_build_object('request_id', declined.id, 'book_id', v_book.id)
  from declined;

  insert into public.notifications (user_id, type, title, body, data)
  values
    (
      v_request.requester_id,
      'request_approved',
      'Book request approved',
      'The owner approved your request.',
      jsonb_build_object('request_id', v_request.id, 'loan_id', v_loan_id, 'book_id', v_book.id)
    ),
    (
      v_request.requester_id,
      'loan_started',
      'Loan started',
      'Your 21-day loan has started.',
      jsonb_build_object('loan_id', v_loan_id, 'book_id', v_book.id)
    ),
    (
      v_book.owner_id,
      'loan_started',
      'Loan started',
      'A 21-day loan has started for your book.',
      jsonb_build_object('loan_id', v_loan_id, 'book_id', v_book.id)
    );

  return v_loan_id;
end;
$$;

create or replace function public.decline_borrow_request(p_request_id uuid)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_actor_id uuid;
  v_request public.borrow_requests%rowtype;
begin
  v_actor_id := (select auth.uid());

  if v_actor_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  select br.*
  into v_request
  from public.borrow_requests as br
  where br.id = p_request_id
  for update;

  if not found then
    raise exception 'Request not found.' using errcode = 'P0002';
  end if;

  if v_request.owner_id <> v_actor_id then
    raise exception 'Only the book owner can decline this request.' using errcode = '42501';
  end if;

  if v_request.status <> 'pending' then
    raise exception 'Only pending requests can be declined.' using errcode = 'P0001';
  end if;

  if v_request.expires_at <= now() then
    raise exception 'This request has expired.' using errcode = 'P0001';
  end if;

  update public.borrow_requests
  set status = 'declined',
      responded_at = now()
  where id = v_request.id;

  insert into public.notifications (user_id, type, title, body, data)
  values (
    v_request.requester_id,
    'request_declined',
    'Book request declined',
    'The owner declined your request.',
    jsonb_build_object('request_id', v_request.id, 'book_id', v_request.book_id)
  );
end;
$$;

