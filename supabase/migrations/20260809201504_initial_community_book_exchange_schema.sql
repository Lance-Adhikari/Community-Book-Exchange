-- SECURITY DEFINER is required because an auth trigger must insert a profile
-- before the new user can hold normal application privileges.
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_display_name text;
begin
  v_display_name := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''),
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    'Community member'
  );

  insert into public.profiles (id, display_name)
  values (new.id, v_display_name);

  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

-- SECURITY DEFINER is required so request ownership is derived from the book
-- and cannot be forged by a client. The trigger also fixes requester_id to auth.uid().
create or replace function private.prepare_borrow_request()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_actor_id uuid;
  v_owner_id uuid;
begin
  v_actor_id := (select auth.uid());

  if v_actor_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  select b.owner_id
  into v_owner_id
  from public.books as b
  where b.id = new.book_id
    and b.is_active
    and b.status = 'available';

  if v_owner_id is null then
    raise exception 'The book is not available for requests.' using errcode = 'P0001';
  end if;

  if v_owner_id = v_actor_id then
    raise exception 'A user cannot request their own book.' using errcode = '23514';
  end if;

  new.requester_id := v_actor_id;
  new.owner_id := v_owner_id;
  new.status := 'pending';
  new.expires_at := now() + interval '72 hours';
  new.responded_at := null;
  new.cancelled_at := null;

  return new;
end;
$$;

revoke all on function private.prepare_borrow_request() from public, anon, authenticated;

create trigger borrow_requests_prepare_insert
before insert on public.borrow_requests
for each row execute function private.prepare_borrow_request();

